/* Needle sweep: 0 -> 270 in 10 s, then 270 -> 0 in 10 s, repeating. */
#define NEEDLE_SWEEP_MS  10000U
#define NEEDLE_ANGLE_MAX 270
#define NEEDLE_CYCLE_MS  (2U * NEEDLE_SWEEP_MS)

static int32_t needle_angle_at(uint32_t elapsed_ms)
{
  uint32_t phase = elapsed_ms % NEEDLE_CYCLE_MS;

  if (phase < NEEDLE_SWEEP_MS)
  {
    return (int32_t)((phase * (uint32_t)NEEDLE_ANGLE_MAX) / NEEDLE_SWEEP_MS);
  }

  return NEEDLE_ANGLE_MAX - (int32_t)(((phase - NEEDLE_SWEEP_MS) * (uint32_t)NEEDLE_ANGLE_MAX) / NEEDLE_SWEEP_MS);
}

/* LVGL task: runs timers/rendering only; heavy drawing is handed to the draw thread. */
static void LVGL_Task(void *argument)
{
  LV_UNUSED(argument);

  uint32_t sweep_start = lv_tick_get();
  int32_t needle_angle = -1;

  for (;;)
  {
    int32_t angle = needle_angle_at(lv_tick_elaps(sweep_start));

    if (angle != needle_angle)
    {
      lv_subject_set_int(subject_needle_angle, angle);
      needle_angle = angle;
    }

    uint32_t wait_ms = lv_timer_handler();

    if (wait_ms == LV_NO_TIMER_READY)
    {
      wait_ms = LV_DEF_REFR_PERIOD;
    }
    else if (wait_ms < 1U)
    {
      wait_ms = 1U;
    }

    lv_sleep_ms(wait_ms);
  }
}
